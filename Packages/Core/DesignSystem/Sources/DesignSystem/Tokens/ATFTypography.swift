// Packages/Core/DesignSystem/Sources/DesignSystem/Tokens/ATFTypography.swift
import SwiftUI

// MARK: - Font tokens

public extension Font {
    // Display — Instrument Serif (bundled via SPM resources)
    // Every token scales with the user's text size setting (Dynamic Type); default sizes unchanged.
    static let atfTitle           = serifFont("InstrumentSerif-Regular",  size: 24, relativeTo: .title2)

    // System text styles (default sizes: title3 20, body 17, subheadline 15, footnote 13, caption2 11)
    static let atfHeadline = Font.system(.title3, weight: .semibold)
    static let atfBody     = Font.system(.body)
    static let atfBodyStr  = Font.system(.body, weight: .semibold)
    static let atfSubhead  = Font.system(.subheadline)
    static let atfCaption  = Font.system(.footnote, weight: .medium)
    static let atfOverline = Font.system(.caption2, weight: .semibold)
    static let atfMono     = Font.system(.subheadline, design: .monospaced, weight: .medium)
}

// Returns Font.custom if the font file is present in the module bundle, else system serif fallback.
// Bundle.module is generated by SPM for packages with resources and is safe from any context.
// bundle.url(forResource:withExtension:) is not @MainActor — safe in any context.
private func serifFont(_ name: String, size: CGFloat, relativeTo style: Font.TextStyle) -> Font {
    let bundle = Bundle.module
    let found = bundle.url(forResource: name, withExtension: "ttf") != nil
    return found
        ? .custom(name, size: size, relativeTo: style)
        : .system(style, design: .serif, weight: .light)
}
