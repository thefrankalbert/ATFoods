import SwiftUI

// MARK: - Font tokens

public extension Font {
    // Display — Instrument Serif (bundled via SPM resources)
    static let atfDisplay         = serifFont("InstrumentSerif-Regular",  size: 34)
    static let atfDisplaySm       = serifFont("InstrumentSerif-Regular",  size: 28)
    static let atfTitle           = serifFont("InstrumentSerif-Regular",  size: 24)
    static let atfDisplayItalic   = serifFont("InstrumentSerif-Italic",   size: 34)
    static let atfDisplaySmItalic = serifFont("InstrumentSerif-Italic",   size: 28)

    // System — Inter via -apple-system
    static let atfHeadline = Font.system(size: 20, weight: .semibold)
    static let atfBody     = Font.system(size: 17, weight: .regular)
    static let atfBodyStr  = Font.system(size: 17, weight: .semibold)
    static let atfSubhead  = Font.system(size: 15, weight: .regular)
    static let atfCaption  = Font.system(size: 13, weight: .medium)
    static let atfOverline = Font.system(size: 11, weight: .semibold)
    static let atfMono     = Font.system(size: 15, weight: .medium, design: .monospaced)
}

// Returns Font.custom if the font file is present in the module bundle, else system serif fallback.
// Bundle.module is generated by SPM for packages with resources and is safe from any context.
// bundle.url(forResource:withExtension:) is not @MainActor — safe in any context.
private func serifFont(_ name: String, size: CGFloat) -> Font {
    let bundle = Bundle.module
    let found = bundle.url(forResource: name, withExtension: "ttf") != nil
    return found
        ? .custom(name, fixedSize: size)
        : .system(size: size, weight: .light, design: .serif)
}

// MARK: - ATFOverlineModifier

public struct ATFOverlineModifier: ViewModifier {
    public init() {}

    public func body(content: Content) -> some View {
        content
            .font(.atfOverline)
            .textCase(.uppercase)
            .tracking(1.0)
            .foregroundStyle(Color.atfText3)
    }
}

public extension View {
    func atfOverlineStyle() -> some View {
        modifier(ATFOverlineModifier())
    }
}
